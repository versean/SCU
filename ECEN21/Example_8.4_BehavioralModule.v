// *****************************************************************************
// this module describes the structural model of logic function in Example 8.4
// *****************************************************************************
module StructuralModel(In1, In2, In3, In4, Out);
  // ***************************************************************************
  // input and output port
  // ***************************************************************************
  input  In1, In2, In3, In4;
  output Out;

  // ***************************************************************************
  // wire connections within module
  // ***************************************************************************
  wire g, h;

  /// ***************************************************************************
  // logic connections
  // ***************************************************************************
  assign g = (In1 & In3) | (In2 & In4);
  assign h = (In1 | ~In3) & (~In2 | In4);
  assign Out = g | h;
endmodule

