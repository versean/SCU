module XOR (A, B, Out);
  input A, B;
  output Out;
  assign Out = A^B;
endmodule //

// *****************************************************************************
// this module for N-bit full adder using behavior model
// *****************************************************************************
module NFullAdder(InA, InB, Cin, Sum, Cout);
  // ***************************************************************************
  // N is the number of bits
  // ***************************************************************************
  parameter  N = 4;

  // ***************************************************************************
  // set inputs and outputs
  // ***************************************************************************
  input  [N-1:0] InA, InB;
  input  Cin;
  output [N-1:0] Sum;
  output Cout;

  // ***************************************************************************
  // set the result for addition
  // ***************************************************************************
  wire   [N:0] AddVal;

  // ***************************************************************************
  // get the result
  // ***************************************************************************
  assign AddVal = InA + InB + Cin;
  assign Sum  = AddVal[N-1:0];
  assign Cout = AddVal[N];
endmodule

// *****************************************************************************
// this module for N-bit full adder using behavior model
// *****************************************************************************
module FullAddSub(InA, InB, CltSig, Sum, Cout);
  // ***************************************************************************
  // N is the number of bits
  // ***************************************************************************
  parameter  N = 4;

  // ***************************************************************************
  // set inputs and outputs
  // ***************************************************************************
  input  [N-1:0] InA, InB;
  input  Cin, CltSig;
  output [N-1:0] Sum;
  output Cout;

  // ***************************************************************************
  // set the result for addition
  // ***************************************************************************
  reg    [N-1:0] OutXor;
  // reg    Cin[0];
  // wire   CltSig;

  // ***************************************************************************
  // check for mode operation
  // ***************************************************************************
  always @* begin
    if (CltSig) begin
      // subtract operation
      OutXor = ~InB;
      // Cin = 1'b1;
    end
    else
      // add operation
      OutXor = InB;
  end

  // ***************************************************************************
  // adding operation
  // ***************************************************************************
  NFullAdder FAU0(.InA(InA), .InB(OutXor), .Cin(CltSig), .Sum(Sum), .Cout(Cout));
  defparam FAU0.N = N;

endmodule //

// *****************************************************************************
// this module generate truth table of variables
// *****************************************************************************
module GenInputPattern(Out, Clk, Reset);
  parameter  N = 8;
  output    [N-1:0] Out;
  input     Clk, Reset;

  // calculate maximum value of output
  localparam  MaxVal = 2 ** N - 1;

  // ***************************************************************************
  // type of output and inputs
  // ***************************************************************************
  wire 	    Clk, Reset;

  // ***************************************************************************
  // type reg because it is used on right hand side (RHS)
  // inside "always" block
  // ***************************************************************************
  reg       [N-1:0] Out;

  // ***************************************************************************
  // logic block
  // ***************************************************************************
  always @(posedge Clk or posedge Reset)
    if (Reset)
      Out <= 0;
    else if (Out >= MaxVal)
      Out <= 0;
    else
      Out <= Out + 1;
endmodule

// *****************************************************************************
// this module generate random number between 0 to 2^N - 1
// *****************************************************************************
module RandomGen(Clk, Out);
  parameter  N = 8;
  input  Clk;
  output [N-1:0] Out;

  // ***************************************************************************
  // calculate maximum value
  // ***************************************************************************
  localparam  MaxVal = 2 ** N - 1;

  // ***************************************************************************
  // define variable type
  // ***************************************************************************
  reg [N-1:0] Out;
  wire   Clk;

  // ***************************************************************************
  // logic block
  // ***************************************************************************
  always @(posedge Clk) begin
    Out = $urandom % MaxVal;
  end
endmodule

